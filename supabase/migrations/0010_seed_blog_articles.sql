A strong motivation letter helps a selection panel understand why you are applying, what you have done to prepare, and how the opportunity connects to a realistic next step. It is not a list of every achievement in your CV, and it cannot guarantee an award. Your job is to answer the prompt with evidence the panel can assess.

## Start with the scholarship''s actual criteria

Read the current application instructions before drafting. Note the exact question, word limit, eligibility rules, selection criteria and deadline. If the provider asks about leadership, do not assume that a general statement about ambition answers it. Look for the behaviour or contribution the panel says it values.

Make a short checklist from the criteria. For each item, write down one experience, result or example you can explain. Mark any criterion for which you do not yet have clear evidence; do not try to hide a gap with a broad claim.

## Choose evidence that shows your contribution

Select examples that make your role visible. Explain the situation, what you were responsible for, the choices you made, and what changed. Use a result where you can support it, but do not invent numbers or claim a team outcome as an individual result.

Paid work is not the only useful evidence. Research, study, volunteering, family responsibilities and community work can all demonstrate relevant skills when you explain the context and your own contribution. Choose the example that best answers the criterion, not simply the one with the most impressive-sounding title.

## Connect your goals to the opportunity

Explain what you want to learn or do next and why this scholarship is relevant. Refer to confirmed features of the award or programme, such as its stated purpose, eligible study route or community focus. Then show the link between that feature, your preparation and the contribution you hope to make.

Avoid relying on praise such as "world-class" or "prestigious" without explaining why the opportunity fits your plans. Check all programme and funding details against current information from the official provider.

## Plan the letter before writing

Use a simple structure that follows the prompt:

